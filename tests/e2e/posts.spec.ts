import { test, expect } from '@playwright/test';
import { randomUUID, randomBytes, createHash } from 'node:crypto';
import { createDatabase, BrandRepository, LedgerRepository } from '../../packages/db/src/index';
import { BrandService } from '../../packages/core/src/brands';
import { emptyOnboarding } from '../../packages/types/src/index';
const url=process.env.TEST_DATABASE_URL;
if(!url||!new URL(url).pathname.endsWith('_test'))throw new Error('Dedicated test database required');
const database=createDatabase(url);test.afterAll(()=>database.close());
test('Post writer generates, versions, approves and copies into calendar',async({page,context,baseURL},testInfo)=>{
  const user=randomUUID(),token=randomBytes(32).toString('base64url'),correlation=randomUUID();
  const brands=new BrandService(new BrandRepository(database.db));
  await database.client`insert into users(id,email,password_hash,name,email_verified_at) values(${user},${`${user}@example.test`},'unusable','Review browser',now())`;
  await database.client`insert into sessions(user_id,token_hash,expires_at) values(${user},${createHash('sha256').update(token).digest('hex')},now()+interval '1 hour')`;
  const tenant=(await brands.createOrganization(user,{name:'Review browser'},correlation)).id;
  try{
    const workspace=(await brands.overview(user,tenant)).workspaces[0]!;
    const brand=(await brands.createBrand(user,tenant,{name:'Review brand',workspaceId:workspace.id},correlation)).id;
    await brands.saveOnboarding(user,tenant,brand,{revision:0,step:14,complete:true,data:{...emptyOnboarding('Review brand'),niche:'Education',geography:'Online',usp:'Practice',voice:'Calm',goals:['Trust'],platforms:['TELEGRAM'],products:[{name:'Course',description:''}],audience:[{name:'Students',description:''}],pains:[{name:'Time',description:''}],ctas:[{name:'Read',description:''}]}},correlation);
    await new LedgerRepository(database.db).adjust(tenant,'AI_CREDITS',10,'posts-browser',correlation);
    await context.addCookies([{name:'contentos_session',value:token,url:baseURL!,httpOnly:true,sameSite:'Lax'}]);
    const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
    await page.goto(`/brands/${brand}/content?organization=${tenant}&tab=posts`);
    await page.getByLabel('Тема поста',{exact:true}).fill('Бумажные модели');
    await page.getByRole('button',{name:'Создать пост · 2 кр.',exact:true}).click();
    await expect(page.getByLabel('Сохранённый пост',{exact:true}).locator('option')).toHaveCount(2,{timeout:60000});
    const endpoint=`/api/organizations/${tenant}/brands/${brand}`;
    const overview=(await (await page.request.get(`${endpoint}/content`)).json()).data;
    const post=overview.posts[0];expect(overview.usage.balances.AI_CREDITS.available).toBe(8);
    await page.getByLabel('Сохранённый пост',{exact:true}).selectOption(post.id);
    await page.getByLabel('Текст поста',{exact:true}).fill('Отредактированный текст поста');
    await expect(page.getByRole('button',{name:'Одобрить пост',exact:true})).toBeDisabled();
    await page.getByRole('button',{name:'Сохранить версию поста',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Пост v2',exact:true})).toBeVisible();
    await page.getByRole('button',{name:'Одобрить пост',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Пост v2 · Одобрен',exact:true})).toBeVisible();
    await page.getByRole('button',{name:'История поста',exact:true}).click();
    await expect(page.getByText('Пост: версия 1',{exact:true})).toBeVisible();
    await page.getByRole('button',{name:'Создать план из поста',exact:true}).click();
    await expect(page.getByLabel('Текст публикации',{exact:true})).toHaveValue('Отредактированный текст поста');
    await page.getByRole('button',{name:'Сохранить план',exact:true}).click();
    await expect(page.getByText('Материал сохранён в плане',{exact:true})).toBeVisible();
    expect(await database.client`select id from publishing_jobs where tenant_id=${tenant}`).toHaveLength(0);
    await page.getByRole('button',{name:'Посты',exact:true}).click();
    await page.getByLabel('Сохранённый пост',{exact:true}).selectOption(post.id);
    await page.reload();await page.getByLabel('Сохранённый пост',{exact:true}).selectOption(post.id);
    await expect(page.getByRole('heading',{name:'Пост v2 · Одобрен',exact:true})).toBeVisible();
    expect((await page.request.put(`${endpoint}/posts/${post.id}`,{data:{revision:2,content:null}})).status()).toBe(403);
    const history=await page.request.get(`${endpoint}/posts/${post.id}`);expect(history.headers()['cache-control']).toBe('no-store');expect((await history.json()).data).toHaveLength(2);
    await page.setViewportSize({width:390,height:844});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);await page.screenshot({path:testInfo.outputPath('posts-mobile.png'),fullPage:true});
    await database.client`update organization_members set role='VIEWER' where tenant_id=${tenant} and user_id=${user}`;
    await page.reload();await page.getByLabel('Сохранённый пост',{exact:true}).selectOption(post.id);await expect(page.getByLabel('Текст поста',{exact:true})).toHaveAttribute('readonly','');
    expect((await page.request.put(`${endpoint}/posts/${post.id}`,{headers:{origin:baseURL!},data:{revision:2,content:{...post.content,body:'Denied'}}})).status()).toBe(403);
    expect(errors).toEqual([]);
  }finally{await database.client`delete from sessions where user_id=${user}`;}
});
