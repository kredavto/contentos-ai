import { test, expect } from '@playwright/test';
import { randomUUID, randomBytes, createHash } from 'node:crypto';
import { createDatabase, BrandRepository } from '../../packages/db/src/index';
import { BrandService } from '../../packages/core/src/brands';
import { emptyOnboarding } from '../../packages/types/src/index';
const url = process.env.TEST_DATABASE_URL;
if (!url || !new URL(url).pathname.endsWith('_test')) throw new Error('Dedicated test database required');
const database = createDatabase(url);
test.afterAll(() => database.close());
test('UTM links preview, persist, copy and archive in the brand studio', async ({ page, context, baseURL }, testInfo) => {
  const user = randomUUID(), token = randomBytes(32).toString('base64url'), correlation = randomUUID();
  const brands = new BrandService(new BrandRepository(database.db));
  await database.client`insert into users(id,email,password_hash,name,email_verified_at) values(${user},${`${user}@example.test`},'unusable','UTM browser',now())`;
  await database.client`insert into sessions(user_id,token_hash,expires_at) values(${user},${createHash('sha256').update(token).digest('hex')},now()+interval '1 hour')`;
  const tenant = (await brands.createOrganization(user,{name:'UTM browser'},correlation)).id;
  try {
    const workspace = (await brands.overview(user,tenant)).workspaces[0]!;
    const brand = (await brands.createBrand(user,tenant,{name:'UTM brand',workspaceId:workspace.id},correlation)).id;
    await brands.saveOnboarding(user,tenant,brand,{revision:0,step:14,complete:true,data:{...emptyOnboarding('UTM brand'),niche:'Education',geography:'Online',usp:'Practice',voice:'Calm',goals:['Trust'],platforms:['TELEGRAM'],products:[{name:'Course',description:''}],audience:[{name:'Students',description:''}],pains:[{name:'Time',description:''}],ctas:[{name:'Read',description:''}]}},correlation);
    await context.addCookies([{name:'contentos_session',value:token,url:baseURL!,httpOnly:true,sameSite:'Lax'}]);
    await context.grantPermissions(['clipboard-read','clipboard-write'],{origin:baseURL!});
    const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
    const endpoint=`/api/organizations/${tenant}/brands/${brand}/utm`;
    await page.goto(`/brands/${brand}/content?organization=${tenant}&tab=utm`);
    await expect(page.getByRole('heading',{name:'UTM-ссылки',exact:true})).toBeVisible();
    await page.getByLabel('Название ссылки',{exact:true}).fill('Осенний запуск');
    await page.getByLabel('Адрес страницы',{exact:true}).fill('https://example.com/course?keep=1&utm_source=old#offer');
    await page.getByLabel('Источник (utm_source)',{exact:true}).fill('telegram');
    await page.getByLabel('Кампания (utm_campaign)',{exact:true}).fill('Осень 2026');
    const preview=await page.getByLabel('Предпросмотр ссылки',{exact:true}).inputValue();
    expect(new URL(preview).searchParams.get('utm_campaign')).toBe('Осень 2026');expect(new URL(preview).hash).toBe('#offer');
    expect((await page.request.post(endpoint,{data:{}})).status()).toBe(403);
    await page.getByRole('button',{name:'Сохранить UTM-ссылку',exact:true}).click();
    await expect(page.getByLabel('Сохранённая ссылка: Осенний запуск',{exact:true})).toHaveValue(preview);
    await page.reload();await expect(page.getByLabel('Сохранённая ссылка: Осенний запуск',{exact:true})).toHaveValue(preview);
    await page.getByRole('button',{name:'Копировать Осенний запуск',exact:true}).click();
    await expect(page.getByRole('status').filter({hasText:'Ссылка скопирована.'})).toBeVisible();
    expect(await page.evaluate(()=>navigator.clipboard.readText())).toBe(preview);
    const response=await page.request.get(endpoint);expect(response.headers()['cache-control']).toBe('no-store');
    const body=await response.json();expect(body.data.rows).toHaveLength(1);expect(JSON.stringify(body)).not.toContain('inputHash');
    await page.setViewportSize({width:390,height:844});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    await page.screenshot({path:testInfo.outputPath('utm-mobile.png'),fullPage:true});
    await page.getByRole('button',{name:'В архив',exact:true}).click();await expect(page.getByText('В этом списке ссылок нет.',{exact:true})).toBeVisible();
    await page.getByLabel('Состояние ссылок',{exact:true}).selectOption('ARCHIVED');
    await expect(page.getByLabel('Сохранённая ссылка: Осенний запуск',{exact:true})).toHaveValue(preview);
    await page.getByRole('button',{name:'Восстановить',exact:true}).click();
    await page.getByLabel('Состояние ссылок',{exact:true}).selectOption('ACTIVE');
    await expect(page.getByLabel('Сохранённая ссылка: Осенний запуск',{exact:true})).toHaveValue(preview);
    await database.client`update organization_members set role='VIEWER' where tenant_id=${tenant} and user_id=${user}`;
    await page.reload();await expect(page.getByRole('button',{name:'Сохранить UTM-ссылку',exact:true})).toHaveCount(0);
    expect((await page.request.post(`${endpoint}/${body.data.rows[0].id}/archive`,{headers:{origin:baseURL!},data:{revision:2,archived:true}})).status()).toBe(403);
    expect(errors).toEqual([]);
  } finally {await database.client`delete from sessions where user_id=${user}`;}
});
